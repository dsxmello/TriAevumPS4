#!/usr/bin/env python3
"""Turns a closure.py JSON (the oot3d_native_game target closure of a host
configure of TriAevum) into a CMake include for the PS4 product build: one
OBJECT library per TriAevum target, with that target's own compile
definitions, include directories and semantic flags, paths remapped from the
host build to this build root (vendored FetchContent deps, the PS4 SDL2).

  gen_cmake.py CLOSURE_JSON HOST_BUILD_DIR OUT_CMAKE

Host-only or replaced sources are dropped here (see EXCLUDED); everything
else compiles as the desktop product does."""
import json, os, re, sys

closure_path, host_build, out_path = sys.argv[1:4]
closure = json.load(open(closure_path))
host_build = os.path.realpath(host_build)

# Replaced on the PS4: the OpenGL renderer/ImGui backend (the PS4 has its own
# Vulkan backend), and the dynamic title-plugin stub (the title is linked
# statically into the eboot).
EXCLUDED = (
    "/src/fast/backends/gfx_opengl.cpp",
    "/src/fast/backends/gfx_opengl_pica.cpp",
    "/backends/imgui_impl_opengl3.cpp",
    "/native_game_runtime/triaevum_title_aot_stub.cpp",
)
SKIP_TARGETS = {"triaevum_title_aot_stub"}
# Flags that carry semantics (kept); optimization/codegen comes from the PS4
# toolchain.
# Host-detected renderer switches: the PS4 has neither OpenGL nor the
# desktop Vulkan/NRI backend (it brings its own).
DROP_DEFINES = {"ENABLE_OPENGL", "ENABLE_OOT3D_VULKAN"}
KEEP_FLAG = re.compile(r"^(-ffp-contract=\S+|-ffp-model=\S+|-std=\S+|-w|-W\S+)$")


def remap(path):
    p = path
    deps = os.path.join(host_build, "_deps")
    if p.startswith(deps):
        rest = os.path.relpath(p, deps)
        head, _, tail = rest.partition("/")
        name = head[:-4] if head.endswith("-src") else head
        if name == "zstd-build":
            return None  # build-tree include of zstd's CMake; not needed
        return "${PS4_DEPS}/" + name + ("/" + tail if tail else "")
    if p.startswith(os.path.join(host_build, "triaevum-product")):
        return "${PS4_PRODUCT_GENERATED}"
    if p == os.path.join(host_build, "three_ds_recomp_runtime/src"):
        return "${PS4_PRODUCT_GENERATED}/three_ds_recomp_runtime"  # ship/install_config.h
    if p.startswith(host_build):
        return None  # empty build-tree dirs (no generated headers there)
    if p == "/usr/include/SDL2":
        return "${PS4_SDL2}/include/SDL2"
    if p.startswith("/usr/"):
        raise SystemExit(f"unexpected host include: {p}")
    return p.replace(os.path.realpath(os.environ.get("TRIAEVUM_ROOT", "/nonexistent")),
                     "${TRIAEVUM_ROOT}")


def cmake_list(items):
    return "\n".join(f"    \"{i}\"" for i in items)


out = ["# Generated by tools/product/gen_cmake.py from the TriAevum host",
       "# configure closure of oot3d_native_game. Do not edit by hand.", ""]
names = []
for target in closure:
    if target["name"] in SKIP_TARGETS:
        continue
    lib = "tri_" + re.sub(r"[^A-Za-z0-9_]", "_", target["name"])
    by_group = {}
    for source in target["sources"]:
        path = source["path"]
        if any(path.endswith(x) for x in EXCLUDED):
            continue
        by_group.setdefault(source["group"], []).append(remap(path) or path)
    if not by_group:
        continue
    names.append(lib)
    all_sources = [s for group in sorted(by_group) for s in by_group[group]]
    out.append(f"# {target['name']} ({target['type']})")
    out.append(f"add_library({lib} OBJECT\n{cmake_list(all_sources)})")
    # One compile group per (language, flags) in practice; definitions and
    # includes are identical across a target's groups except for language
    # flags, so they attach per source group.
    for group_index, sources in sorted(by_group.items()):
        group = target["groups"][group_index]
        defines = [d.replace('"', '\\"') for d in group["defines"]
                   if d.split("=")[0] not in DROP_DEFINES]
        includes = [i for i in (remap(x) for x in group["includes"]) if i]
        flags = [f for frag in group["flags"] for f in frag.split() if KEEP_FLAG.match(f)]
        props = []
        if defines:
            props.append("COMPILE_DEFINITIONS \"" + ";".join(defines) + "\"")
        if includes:
            props.append("INCLUDE_DIRECTORIES \"" + ";".join(includes) + "\"")
        if flags:
            props.append("COMPILE_OPTIONS \"" + ";".join(flags) + "\"")
        if props:
            out.append(f"set_source_files_properties(\n{cmake_list(sources)}\n"
                       f"    TARGET_DIRECTORY {lib}\n    PROPERTIES {' '.join(props)})")
    # The first group's definitions/includes, for sources added by the PS4
    # port that compile against this target's headers.
    first = target["groups"][sorted(by_group)[0]]
    out.append(f"set({lib}_DEFINES \"" + ";".join(
        d.replace('"', '\\"') for d in first["defines"]
        if d.split("=")[0] not in DROP_DEFINES) + "\")")
    out.append(f"set({lib}_INCLUDES \"" + ";".join(
        i for i in (remap(x) for x in first["includes"]) if i) + "\")")
    out.append("")
out.append("set(TRIAEVUM_PRODUCT_OBJECT_LIBRARIES\n" + cmake_list(names) + ")")
open(out_path, "w").write("\n".join(out) + "\n")
print(f"{len(names)} object libraries, "
      f"{sum(len(t['sources']) for t in closure)} closure sources -> {out_path}")
